require('./helpers/offline')
const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('fs')
const path=require('path')
const sql=fs.readFileSync(path.join(__dirname,'../scripts/migrations/0153-task-assignment-lifecycle.sql'),'utf8')
test('B3 migration prepares transactional project-scoped AFTER lifecycle safeguards',()=>{
 assert.match(sql,/BEGIN;/);assert.match(sql,/COMMIT;\s*$/)
 assert.match(sql,/AFTER DELETE ON project_memberships FOR EACH ROW/)
 assert.match(sql,/AFTER UPDATE OF owner_id ON source_projects FOR EACH ROW/)
 assert.match(sql,/WHEN \(OLD.owner_id IS DISTINCT FROM NEW.owner_id\)/)
 assert.match(sql,/current_owner IS DISTINCT FROM OLD.user_id/)
 assert.match(sql,/WHERE project_id=\$1 AND assignee_user_id=\$2/)
 assert.match(sql,/NOT EXISTS \(SELECT 1 FROM %I.project_memberships/)
 assert.match(sql,/SET assignee_user_id=NULL,updated_at=now\(\)/)
 assert.match(sql,/ERRCODE = '40001'/)
 assert.doesNotMatch(sql,/ALTER TABLE|FOREIGN KEY|SECURITY DEFINER|DROP |CREATE OR REPLACE/)
 for(const field of ['title','description','status','priority','creator_id','sprint_id'])assert.doesNotMatch(sql,new RegExp(`${field}\\s*=`))
})
