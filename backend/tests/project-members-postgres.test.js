require('./helpers/offline')
const {test}=require('node:test')
const assert=require('node:assert/strict')
const crypto=require('crypto')
const fs=require('fs')
const path=require('path')
const {Pool}=require('pg')
const {createMembershipRepository}=require('../src/db/membershipRepository')
// Explicit disposable test database only. Never falls back to DATABASE_URL.
test('PostgreSQL membership constraints, restart persistence, concurrent duplicates and ownership transfer',{skip:!process.env.MEMBERSHIP_TEST_DATABASE_URL},async()=>{
 const connectionString=process.env.MEMBERSHIP_TEST_DATABASE_URL,schema='membership_test_'+crypto.randomBytes(8).toString('hex')
 const admin=new Pool({connectionString,connectionTimeoutMillis:5000});let pool,restarted
 try{
  await admin.query(`CREATE SCHEMA ${schema}`)
  const options={connectionString,options:`-c search_path=${schema}`,connectionTimeoutMillis:5000}
  pool=new Pool(options)
  await pool.query('CREATE TABLE users(id UUID PRIMARY KEY,full_name VARCHAR(150) NOT NULL,email VARCHAR(255) UNIQUE NOT NULL,role VARCHAR(50) NOT NULL)')
  for(const file of ['0132-source-workspace.sql','0146-project-tasks.sql','0147-project-sprints.sql','0148-project-memberships.sql','0152-task-assignment.sql'])await pool.query(fs.readFileSync(path.join(__dirname,'../scripts/migrations',file),'utf8'))
  const owner=crypto.randomUUID(),member=crypto.randomUUID(),other=crypto.randomUUID()
  for(const [id,email] of [[owner,'owner@directory.test'],[member,'member@directory.test'],[other,'other@directory.test']])await pool.query("INSERT INTO users VALUES($1,'Registered',$2,'Developer')",[id,email])
  await pool.query('INSERT INTO source_projects(id,owner_id,name) VALUES($1,$2,$3),($4,$5,$6)',['owned',owner,'Owned','foreign',other,'Foreign'])
  let repo=createMembershipRepository(pool)
  const input={projectId:'owned',email:'MEMBER@directory.test',displayRole:'Tester'}
  const results=await Promise.allSettled([repo.create(input,owner),repo.create(input,owner)])
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);assert.equal(results.find(r=>r.status==='rejected').reason.code,'member_not_added')
  const saved=results.find(r=>r.status==='fulfilled').value
  await repo.update(saved.id,owner,{displayRole:'Viewer'})
  const client=await pool.connect()
  async function fails(sql,args,code){await client.query('BEGIN');try{await assert.rejects(client.query(sql,args),e=>e.code===code)}finally{await client.query('ROLLBACK')}}
  try{
   const insert='INSERT INTO project_memberships(id,project_id,user_id,added_by,display_role) VALUES($1,$2,$3,$4,$5)'
   await fails(insert,[crypto.randomUUID(),'owned',member,owner,'Tester'],'23505')
   await fails(insert,[crypto.randomUUID(),'missing',other,owner,'Viewer'],'23503')
   await fails(insert,[crypto.randomUUID(),'owned',crypto.randomUUID(),owner,'Viewer'],'23503')
   await fails(insert,[crypto.randomUUID(),'owned',other,crypto.randomUUID(),'Viewer'],'23503')
   await fails(insert,[crypto.randomUUID(),'owned',other,owner,'Project Manager'],'23514')
  }finally{client.release()}
  await pool.end();pool=null;restarted=new Pool(options);repo=createMembershipRepository(restarted)
  let list=await repo.list(owner,{projectId:'owned',limit:'1'});assert.equal(list.members[0].displayRole,'Viewer');assert.equal(list.owner.userId,owner);assert.equal(list.total,1)
  for(const run of [()=>repo.list(other,{projectId:'owned'}),()=>repo.update(saved.id,other,{displayRole:'Tester'}),()=>repo.remove(saved.id,other)])await assert.rejects(run(),e=>e.code==='not_found')
  await restarted.query('UPDATE source_projects SET owner_id=$2 WHERE id=$1',['owned',member])
  await assert.rejects(repo.list(owner,{projectId:'owned'}),e=>e.code==='not_found')
  list=await repo.list(member,{projectId:'owned'});assert.equal(list.total,0);assert.equal(list.owner.userId,member)
  await assert.rejects(repo.remove(saved.id,member),e=>e.code==='not_found')
  const added=await repo.create({...input,email:'owner@directory.test'},member)
  const {createTaskRepository}=require('../src/db/taskRepository'),{createSprintRepository}=require('../src/db/sprintRepository')
  const tasks=createTaskRepository(restarted),sprints=createSprintRepository(restarted)
  const assigned=await tasks.create({projectId:'owned',title:'Keep content',description:'Keep body',status:'Done',priority:'High',assigneeUserId:owner},member)
  const sprint=await sprints.create({projectId:'owned',name:'Keep sprint',startDate:'2026-10-16',endDate:'2026-10-17'},member)
  await sprints.assign(sprint.id,assigned.id,member)
  await restarted.query("UPDATE project_tasks SET updated_at='2001-01-01' WHERE id=$1",[assigned.id])
  const before=await tasks.read(assigned.id,member),sprintBefore=await sprints.read(sprint.id,member)
  const untouched=await tasks.create({projectId:'owned',title:'Other assignee',assigneeUserId:member},member)
  await repo.create({projectId:'foreign',email:'owner@directory.test',displayRole:'Developer'},other)
  const cross=await tasks.create({projectId:'foreign',title:'Other project',assigneeUserId:owner},other)
  await repo.remove(added.id,member)
  const after=await tasks.read(assigned.id,member)
  assert.deepEqual(after,{...before,assigneeUserId:null,assignee:null,updatedAt:after.updatedAt})
  assert(after.updatedAt>before.updatedAt)
  assert.deepEqual(await tasks.read(untouched.id,member),untouched)
  assert.deepEqual(await tasks.read(cross.id,other),cross)
  assert.deepEqual(await sprints.read(sprint.id,member),sprintBefore)
  const racer=await repo.create({projectId:'owned',email:'other@directory.test',displayRole:'Tester'},member)
  const outcomes=await Promise.allSettled([tasks.update(assigned.id,member,{assigneeUserId:other}),repo.remove(racer.id,member)])
  assert.equal(outcomes[1].status,'fulfilled')
  if(outcomes[0].status==='rejected')assert.equal(outcomes[0].reason.code,'assignee_not_eligible')
  assert.equal((await tasks.read(assigned.id,member)).assigneeUserId,null)
  const originalRoles=(await restarted.query('SELECT role FROM users')).rows;assert.ok(originalRoles.every(u=>u.role==='Developer'))
 }finally{if(pool)await pool.end();if(restarted)await restarted.end();await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);await admin.end()}
})
